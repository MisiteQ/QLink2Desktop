// glyphSize 返回字模的宽高（已含 1 像素字间距时请用 GlyphAdvance）。
const (
	glyphWidth   = 5
	glyphHeight  = 7
	glyphSpacing = 1
)

// NormalizeIconText 把任意输入折叠成可渲染的大写短文本。
//
// 规则：只保留字模里存在的字符，最多 4 个字符（图标上再多就糊成一团了）。
func NormalizeIconText(text string) string {
	text = strings.ToUpper(strings.TrimSpace(text))
	var b strings.Builder
	for _, r := range text {
		if _, ok := glyph5x7[r]; ok && r != ' ' {
			b.WriteRune(r)
			if b.Len() >= 4 {
				break
			}
		}
	}
	out := b.String()
	if out == "" {
		return "QL"
	}
	return out
}

// measureText 返回给定文本在点阵下的像素宽度（含字间距）。
func measureText(text string) int {
	glyphs := []rune(NormalizeIconText(text))
	if len(glyphs) == 0 {
		return 0
	}
	return len(glyphs)*glyphWidth + (len(glyphs)-1)*glyphSpacing
}
