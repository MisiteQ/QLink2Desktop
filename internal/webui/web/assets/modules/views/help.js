/* help.js —— 「使用帮助」视图
 *
 * 为什么要有这一页：这个应用的四种能力（本机端口、端口映射、网址快捷方式、
 * 远程主机）在列表里长得几乎一样，但"点开之后会发生什么"完全不同。
 * 用户没有义务从界面上倒推出来 —— 与其把说明散落在各个卡片的 hint 里，
 * 不如集中成一页，每张卡片讲清一件事：它解决什么问题、怎么用、有什么坑。
 *
 * 内容与代码同源、一起发版：文档写在仓库里没人看，写在界面里才会被看到。
 */

import { h, replace, table } from '../dom.js';
import { icon } from '../icons.js';
import { state } from '../store.js';

export const title = '使用帮助';
export const subtitle = () => '外观与重启、几种链接形态的区别、远程主机的用途，以及常见故障怎么排查';

let root = null;

export function mount(container) {
  root = container;
  draw();
}

// refresh 刻意不重绘。
//
// 这是一份长文档：应用每收到一次状态推送都会通知当前视图 refresh，
// 如果跟着重绘，用户读到一半的滚动位置就会被拽回顶部。
// 页面内容本身不依赖运行态，重绘没有任何收益。
export function refresh() {}

function draw() {
  if (!root) return;
  replace(root, [
    quickStart(),
    appearanceCard(),
    kindCard(),
    remoteHostCard(),
    scanCard(),
    iconCard(),
    troubleCard(),
    boundaryCard(),
    aboutCard(),
  ]);
}

/* ------------------------------------------------------------------ 组件 */

function card(iconName, heading, lead, blocks) {
  return h('div', { class: 'card mb-3' }, [
    h('div', { class: 'card-head' }, [
      h('div', {}, [
        h('h2', {}, [icon(iconName, 15), ` ${heading}`]),
        lead ? h('p', { text: lead }) : null,
      ]),
    ]),
    h('div', { class: 'card-body' }, blocks),
  ]);
}

function steps(items) {
  return h('ol', { class: 'help-steps' }, items.map((text) => h('li', { text })));
}

function bullets(items) {
  return h('ul', { class: 'help-list' }, items.map((text) => h('li', { text })));
}

function para(text) {
  return h('p', { class: 'muted', style: { margin: '0 0 10px', lineHeight: '1.7' }, text });
}

function small(text) {
  return h('p', { class: 'muted', style: { margin: '10px 0 0', fontSize: '.78rem', lineHeight: '1.7' }, text });
}

// tableOf 把二维数组渲染成表格；单元格是字符串时自动包成文本节点。
function tableOf(columns, rows) {
  return table(
    columns.map((c) => ({ label: c })),
    rows,
    (row) => h('tr', {}, row.map((cell) => h('td', {}, [
      typeof cell === 'string' ? h('div', { text: cell }) : cell,
    ]))),
  );
}

function code(text) {
  return h('code', { text });
}

function tag(text, cls = '') {
  return h('span', { class: `tag ${cls}`.trim(), text });
}

