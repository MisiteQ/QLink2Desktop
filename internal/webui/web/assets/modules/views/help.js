/* ---------------------------------------------------------- 局域网扫描 */

function scanCard() {
  const info = state.scan?.info;
  const primary = info?.primary ? `${info.primary}.0/24` : '（打开服务发现页后可见）';

  return card('wifi', '局域网扫描', '找出同网段其它设备上开放的服务端口，点一下就能放到桌面', [
    para('扫描对象就是飞牛所在网段的其它设备。页面上会先显示探测到的网络环境，' +
      '包含本机 IP、网关、本机网段，以及能推导出来的上级网段。'),

    h('h3', { class: 'help-h3', text: '三种范围' }),
    bullets([
      `本机网段：当前是 ${primary}，扫描这 254 个地址里的其它设备。`,
      '上级网段：只有当默认网关不在本机网段里时才会出现 —— 那种拓扑说明飞牛挂在下游，' +
        '网关所在的那一段才是"上面那层"。网关和本机同段时本段就是最外层，没有可推导的上级，' +
        '这时请用自定义范围。',
      '自定义范围：支持单台 192.168.1.10、整段 192.168.1、区间 192.168.1.10-60、' +
        '掩码 192.168.1.0/24、主机名，多个用逗号分隔。单次上限 1024 台，超了会直接告诉你，' +
        '而不会悄悄只扫一部分。',
    ]),

    h('h3', { class: 'help-h3', text: '为什么要等一会儿' }),
    para('目标是"发很多次 TCP 连接"，一个网段就是上万次，所以它跑在后台：' +
      '开始之后可以切到别的页面，回来时进度还在。目标超过 32 台时会先做一轮在线探测，' +
      '再只对在线设备细扫端口 —— 代价是，如果某台设备在线但一个常见端口都没开，它可能被跳过。' +
      '真遇到这种情况，把它的 IP 单独填进「自定义范围」再扫一次即可。'),
    small('扫描结果里的端口号可以直接点击，会带着 IP 和端口打开编辑器，默认形态是「端口映射」。'),
  ]);
}

